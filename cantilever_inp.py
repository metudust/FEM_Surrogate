"""Write an Abaqus/Standard input file for a 2-D plane-stress cantilever with a tip load.

Geometry : length L along x, height h along y (centred on the neutral axis), thickness b.
Mesh     : nx x ny 8-node quadrilaterals, CPS8R (plane stress, reduced integration).
Supports : root edge (x = 0) has U1 = 0 at every node and U2 = 0 at the mid-height node.
           That clamps the rotation of the root section without the artificial corner
           stress singularity you get from fixing U2 along the whole edge.
Load     : total tip force P in -y, applied as consistent nodal forces for a uniform shear
           traction on the tip edge (1/6, 4/6, 1/6 of each element edge's share).
Steps    : LOAD   ramps P up (NLGEOM on)  -> peak tip deflection
           UNLOAD removes P               -> residual (permanent) tip deflection
Material : isotropic elasticity + linear isotropic hardening (Mises plasticity).
Units    : mm, N, MPa.

Plain Python 3, no Abaqus needed to generate the file.
"""
from pathlib import Path

KAPPA = 5.0 / 6.0  # Timoshenko shear coefficient, rectangular section


def node_count(nx, ny):
    """Nodes in an nx x ny mesh of 8-node quads."""
    return (2 * nx + 1) * (2 * ny + 1) - nx * ny


def derived(p, nu=0.3):
    """Derived quantities and beam-theory references.

    p needs h, b, E and either slenderness or L, and either load_factor or P.
    """
    h, b, E = p["h"], p["b"], p["E"]
    L = p["L"] if "L" in p else p["slenderness"] * h
    I = b * h ** 3 / 12.0
    P_yield = p["sy"] * b * h ** 2 / (6.0 * L) if "sy" in p else float("nan")
    P = p["P"] if "P" in p else p["load_factor"] * P_yield
    G = E / (2.0 * (1.0 + nu))
    delta_EB = P * L ** 3 / (3.0 * E * I)                  # Euler-Bernoulli
    delta_Timo = delta_EB + P * L / (KAPPA * G * b * h)    # + shear deformation
    return {"L": L, "I": I, "P_yield": P_yield, "P": P,
            "delta_EB": delta_EB, "delta_Timo": delta_Timo}


def _nid(i, j, nx):
    # Nodes live on a (2nx+1) x (2ny+1) grid; element centres (i, j both odd) are skipped,
    # which leaves gaps in the numbering. Abaqus accepts that.
    return j * (2 * nx + 1) + i + 1


def build_mesh(L, h, nx, ny):
    """Return nodes {id: (x, y)}, elements [(id, (8 node ids))] and node sets."""
    nodes = {}
    for j in range(2 * ny + 1):
        for i in range(2 * nx + 1):
            if i % 2 == 1 and j % 2 == 1:
                continue
            nodes[_nid(i, j, nx)] = (L * i / (2 * nx), -h / 2.0 + h * j / (2 * ny))
    elems = []
    for ey in range(ny):
        for ex in range(nx):
            i0, j0 = 2 * ex, 2 * ey

            def n(di, dj):
                return _nid(i0 + di, j0 + dj, nx)
            # corners counter-clockwise, then mid-side nodes 1-2, 2-3, 3-4, 4-1
            conn = (n(0, 0), n(2, 0), n(2, 2), n(0, 2), n(1, 0), n(2, 1), n(1, 2), n(0, 1))
            elems.append((ey * nx + ex + 1, conn))
    sets = {
        "ROOT": [_nid(0, j, nx) for j in range(2 * ny + 1)],
        "ROOT_MID": [_nid(0, ny, nx)],
        "TIP": [_nid(2 * nx, j, nx) for j in range(2 * ny + 1)],
        "TIP_MID": [_nid(2 * nx, ny, nx)],
    }
    return nodes, elems, sets


def tip_forces(P, nx, ny):
    """Consistent nodal forces (magnitudes) for a uniform shear traction on the tip edge."""
    f = {}
    for ey in range(ny):
        for dj, w in ((0, 1.0 / 6.0), (1, 4.0 / 6.0), (2, 1.0 / 6.0)):
            k = _nid(2 * nx, 2 * ey + dj, nx)
            f[k] = f.get(k, 0.0) + w * P / ny
    return f


def _g(x):
    return "%.10g" % x


def write_inp(path, p, nx=40, ny=4, nu=0.3, plastic=True, nlgeom=True, unload=True, title=""):
    """Write the .inp file and return a dict of derived values and mesh info."""
    d = derived(p, nu)
    nodes, elems, sets = build_mesh(d["L"], p["h"], nx, ny)
    lines = []
    w = lines.append

    w("*HEADING")
    w(title or "Cantilever with tip load")
    w("** Generated by cantilever_inp.py. Units: mm, N, MPa.")
    info = dict(p)
    info.update(d)
    items = ["%s=%s" % (k, _g(v)) for k, v in info.items() if isinstance(v, (int, float))]
    for c in range(0, len(items), 4):          # Abaqus input lines are limited to 256 characters
        w("** " + ", ".join(items[c:c + 4]))
    w("*PREPRINT, ECHO=NO, MODEL=NO, HISTORY=NO, CONTACT=NO")

    w("*NODE, NSET=ALLN")
    for k in sorted(nodes):
        x, y = nodes[k]
        w("%d, %s, %s" % (k, _g(x), _g(y)))
    w("*ELEMENT, TYPE=CPS8R, ELSET=BEAM")
    for e, conn in elems:
        w("%d, %s" % (e, ", ".join(str(c) for c in conn)))
    for name, ids in sets.items():
        w("*NSET, NSET=%s" % name)
        for c in range(0, len(ids), 16):
            w(", ".join(str(i) for i in ids[c:c + 16]))

    w("*SOLID SECTION, ELSET=BEAM, MATERIAL=MAT")
    w("%s," % _g(p["b"]))                       # plane-stress thickness
    w("*MATERIAL, NAME=MAT")
    w("*ELASTIC")
    w("%s, %s" % (_g(p["E"]), _g(nu)))
    if plastic:
        E, Et = p["E"], p["hard_ratio"] * p["E"]
        H = E * Et / (E - Et)                   # plastic modulus d(sigma)/d(eps_p)
        w("*PLASTIC")
        w("%s, 0." % _g(p["sy"]))
        w("%s, 1." % _g(p["sy"] + H * 1.0))     # linear hardening up to eps_p = 1

    w("*BOUNDARY")
    w("ROOT, 1, 1")
    w("ROOT_MID, 2, 2")

    # ---- step 1: load
    if nlgeom:
        w("*STEP, NAME=LOAD, NLGEOM=YES, INC=1000")
        w("*STATIC")
        w("0.02, 1., 1e-08, 0.05")             # at least 20 increments -> smooth curve
    else:
        w("*STEP, NAME=LOAD, INC=100")
        w("*STATIC")
        w("1., 1., 1e-05, 1.")
    w("*CLOAD")
    for k, f in sorted(tip_forces(d["P"], nx, ny).items()):
        w("%d, 2, %s" % (k, _g(-f)))
    w("*OUTPUT, FIELD, NUMBER INTERVAL=1")     # field output at the end of each step
    w("*NODE OUTPUT")
    w("U, RF")
    w("*ELEMENT OUTPUT")
    w("S, PE, PEEQ" if plastic else "S, E")
    w("*OUTPUT, HISTORY, FREQUENCY=1")         # tip displacement every increment
    w("*NODE OUTPUT, NSET=TIP_MID")
    w("U1, U2")
    w("*END STEP")

    # ---- step 2: unload (output requests carry over from step 1)
    if unload:
        w("*STEP, NAME=UNLOAD, NLGEOM=%s, INC=1000" % ("YES" if nlgeom else "NO"))
        w("*STATIC")
        w("0.05, 1., 1e-08, 0.1")
        w("*CLOAD, OP=NEW")                    # removing the load ramps it to zero
        w("*END STEP")

    Path(path).write_text("\n".join(lines) + "\n", encoding="ascii")
    out = dict(d)
    out.update({"nodes": len(nodes), "elements": len(elems),
                "tip_mid": sets["TIP_MID"][0], "root_mid": sets["ROOT_MID"][0]})
    return out
